function hostPlatform(): string {
    return (globalThis as { process?: { platform?: string } }).process?.platform ?? "linux";
}

function defaultFontSize(platform: string): number {
    if (platform === "darwin") return 12;
    if (platform === "win32") return 10;
    return 11;
}

